import fs from "node:fs";
import path from "node:path";
import { kb } from "../config.mjs";
import { result, today, writeOrCheck } from "../util.mjs";
import { logDir, parseLog, LOG_KINDS } from "./store.mjs";

const RECENT = 15;
const render = (e) => `## [${e.date}] ${e.kind} | ${e.title}\n\n${e.body}\n`;

export function appendLog(cfg, kind, title, notes = [], date = today()) {
  if (!LOG_KINDS.includes(kind)) throw new Error(`log kind must be one of ${LOG_KINDS.join(", ")}`);
  if (!title) throw new Error("log title is required");
  const dir = logDir(cfg);
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${date.slice(0, 7)}.md`);
  if (!fs.existsSync(file)) fs.writeFileSync(file, `# Log ${date.slice(0, 7)}\n`);
  const bullets = notes.length ? notes.map((n) => `- ${n}`).join("\n") : "- Notes: none";
  fs.appendFileSync(file, `\n## [${date}] ${kind} | ${title}\n\n${bullets}\n`);
  return file;
}

export function splitLog(cfg, source) {
  const written = [];
  const byMonth = new Map();
  for (const e of parseLog(fs.readFileSync(source, "utf8"))) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(e.date)) continue;
    const month = e.date.slice(0, 7);
    if (!byMonth.has(month)) byMonth.set(month, []);
    byMonth.get(month).push(e);
  }
  for (const [month, unsorted] of byMonth) {
    const entries = unsorted
      .map((e, i) => ({ e, i }))
      .sort((a, b) => a.e.date.localeCompare(b.e.date) || a.i - b.i)
      .map((x) => x.e);
    const file = path.join(logDir(cfg), `${month}.md`);
    if (fs.existsSync(file)) continue;
    fs.writeFileSync(file, `# Log ${month}\n\n${entries.map(render).join("\n")}`);
    written.push(file);
  }
  return written;
}

export function rollup(cfg, { check = false } = {}) {
  const r = result("log rollup");
  const dir = logDir(cfg);
  const months = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /^\d{4}-\d{2}\.md$/.test(f)).sort() : [];
  const all = [];
  const indexRows = [];

  for (const name of months) {
    const month = name.slice(0, 7);
    const entries = parseLog(fs.readFileSync(path.join(dir, name), "utf8"));
    let previous = "";
    for (const e of entries) {
      if (!e.date.startsWith(month)) r.errors.push(`log/${name}: entry ${e.date} "${e.title}" belongs in log/${e.date.slice(0, 7)}.md`);
      if (e.date < previous) r.errors.push(`log/${name}: entry ${e.date} "${e.title}" is out of date order`);
      previous = e.date;
      all.push({ ...e, month });
    }
    const kinds = [...new Set(entries.map((e) => e.kind))].sort().join(", ");
    indexRows.push(`| [${month}](${name}) | ${entries.length} | ${kinds} |`);
  }

  const index = `# Log Index

Generated by \`npm run rollup\`. One file per month; add entries with \`npm run log -- <kind> "<title>"\`.

| Month | Entries | Kinds |
| --- | --- | --- |
${indexRows.reverse().join("\n")}
`;

  const recent = all.slice(-RECENT).reverse();
  const recentDoc = `# Recent Changes

Generated by \`npm run rollup\` from \`log/\`: the latest ${RECENT} entries, newest first. Read the month file for full notes.

${recent.map((e) => `- ${e.date} **${e.kind}**: ${e.title} ([log/${e.month}.md](../log/${e.month}.md))`).join("\n") || "- No entries yet."}
`;

  for (const [file, content, label] of [
    [path.join(dir, "index.md"), index, "knowledge/log/index.md"],
    [kb(cfg, "synthesis", "recent-changes.md"), recentDoc, "knowledge/synthesis/recent-changes.md"]
  ]) {
    const { changed, ok } = writeOrCheck(file, content, check);
    if (!ok) r.errors.push(`${label} is stale; run npm run rollup`);
    else if (changed) r.notes.push(`wrote ${label}`);
  }
  return r;
}

export const GENERATED = "<!-- generated by max-kit sync; edit the source, not this file -->";

const demote = (md) => md.replace(/^(#+) /gm, "#$1 ").replace(/^## Team Rules\n+/m, "");

export function renderAgentsMd(model, { inlineRules = false } = {}) {
  const repos = model.repos.length
    ? ["| Repo | Path | Profile | Tests |", "| --- | --- | --- | --- |", ...model.repos.map((r) => `| ${r.id} | \`${r.path}\` | ${r.profile} | ${r.testCommand ? `\`${r.testCommand}\`` : ""} |`)].join("\n")
    : "No app repos configured yet; add them to `max-kit.config.json` › `repos`.";
  const commands = ["| Command | Does |", "| --- | --- |", ...model.commands.map(([c, d]) => `| \`${c}\` | ${d} |`)].join("\n");
  const rules = inlineRules
    ? `## Team rules\n\n${demote(model.teamRules)}`
    : `## Team rules\n\nThe single source is \`${model.teamRulesPath}\`. Runtimes with hooks inject it at session start; otherwise read it before the first change.`;
  const branches = [
    model.branches.protected.length ? `- Never push to: ${model.branches.protected.map((b) => `\`${b}\``).join(", ")}. Push a task branch instead.` : "",
    model.branches.deploy.length ? `- Never edit code on: ${model.branches.deploy.map((b) => `\`${b}\``).join(", ")}.` : ""
  ]
    .filter(Boolean)
    .join("\n");

  return `${GENERATED}
# ${model.project}: agent instructions

This folder is the control plane for ${model.project}. Before any non-trivial task read, in order:

${model.readOrder
  .slice(1)
  .map((f, i) => `${i + 1}. \`${f}\``)
  .join("\n")}
${model.readOrder.length}. \`knowledge/harness/features/<ID>.yml\` for the matched feature only

${rules}

## Branches

${branches || "- No protected branches configured."}

## Repos

${repos}

## Commands

${commands}

## Done

No evidence means not done. Record verification in \`knowledge/harness/runs/\` or set the feature to \`blocked\` with the missing env, source, credential, data or decision.
`;
}
